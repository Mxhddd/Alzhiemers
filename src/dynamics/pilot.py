"""Module 4 PILOT screening, run before registration:  python -m src.dynamics.pilot

Exploratory, and disclosed as such in prereg/dynamics.md. It is NOT the
registered analysis and deliberately does not compute any registered fraction
(both drugs protective, U-shape, bistability fraction) or any Sobol index.

* Morris elementary effects (SALib; pilot.seed, its own sample) for continuous
  outputs only: log T*, log T* ratio for each drug at one IC50, and the length
  of the bistable hA window in [0, 1].
* One-at-a-time sweeps: each parameter over its range (on its sampling scale)
  with the others at the reference point.

Writes results/tables/dynamics_pilot_morris.csv, dynamics_pilot_oat.csv and the
generated note manuscript/notes/module4_pilot.md (numbers are never typed by hand).
"""

from __future__ import annotations

import sys

import numpy as np
import pandas as pd

from src.common.config import load_config
from src.common.paths import CONFIG_DIR, REPO_ROOT, TABLES_DIR
from src.common.runlog import start_run
from src.common.validation import require_validated
from src.dynamics import lc_model
from src.dynamics.analysis import Space, evaluate
from src.dynamics.params import ParameterSet

CONFIG = CONFIG_DIR / "dynamics.yaml"
NOTE = REPO_ROOT / "manuscript" / "notes" / "module4_pilot.md"


def main() -> int:
    from SALib.analyze import morris as morris_an
    from SALib.sample import morris as morris_sa

    require_validated("dynamics")
    cfg = load_config(CONFIG)
    params = ParameterSet.from_yaml(CONFIG_DIR / "dynamics_params.yaml")
    space = Space.from_params(params)
    seed = cfg.get("pilot.seed")
    outs = cfg.get("pilot.morris_outputs")
    with start_run(module="dynamics_pilot", config_path=CONFIG, seed=seed, packages=["numpy", "scipy", "SALib"]) as run:
        TABLES_DIR.mkdir(parents=True, exist_ok=True)
        rng_ranges = space.sampling_ranges()
        names = list(rng_ranges)
        problem = {"num_vars": len(names), "names": names, "bounds": [list(rng_ranges[n]) for n in names]}
        X = morris_sa.sample(problem, cfg.get("pilot.morris_trajectories"), num_levels=cfg.get("pilot.morris_levels"),
                             seed=seed)
        rows = [evaluate(space.to_params(dict(zip(names, x))), cfg, with_dose_curves=False) for x in X]
        run.info(f"Morris: {len(X)} evaluations")
        mrows = []
        for o in outs:
            Y = np.array([float(r[o]) for r in rows])
            res = morris_an.analyze(problem, X, Y, num_levels=cfg.get("pilot.morris_levels"), seed=seed)
            scale = max(res["mu_star"]) if max(res["mu_star"]) > 0 else 1.0
            for i, n in enumerate(names):
                mrows.append({"output": o, "parameter": n, "mu_star": res["mu_star"][i],
                              "mu_star_rel": res["mu_star"][i] / scale, "sigma": res["sigma"][i]})
        mdf = pd.DataFrame(mrows)
        mdf.to_csv(TABLES_DIR / "dynamics_pilot_morris.csv", index=False)
        run.record_output(TABLES_DIR / "dynamics_pilot_morris.csv")

        p0 = params.values()
        orows = []
        for n, (lo, hi) in rng_ranges.items():
            for z in np.linspace(lo, hi, cfg.get("pilot.oat_points")):
                p = dict(p0, **{n: float(10 ** z) if space.scales[n] == "log" else float(z)})
                r = evaluate(p, cfg, with_dose_curves=False)
                ss = lc_model.healthy_steady_state(p)
                orows.append({"parameter": n, "value": p[n], "T0": r["T0"], "R0": r["R0"],
                              "ratio_atomoxetine": r["ratio_atomoxetine"], "ratio_prazosin": r["ratio_prazosin"],
                              "n_fixed": ss["n_fixed"], "n_stable": ss["n_stable"],
                              "bistable_window_length": r["bistable_window_length"]})
        odf = pd.DataFrame(orows)
        odf.to_csv(TABLES_DIR / "dynamics_pilot_oat.csv", index=False)
        run.record_output(TABLES_DIR / "dynamics_pilot_oat.csv")
        NOTE.write_text(_note(mdf, odf, len(X), run), encoding="utf-8")
        run.record_output(NOTE)
    return 0


def _note(mdf: pd.DataFrame, odf: pd.DataFrame, n_eval: int, run) -> str:
    L = ["# Module 4 — pilot screening before registration (generated)", "",
         f"> Generated by `src/dynamics/pilot.py` (commit {run.header['git']['commit'][:7]}"
         f"{', dirty tree' if run.header['git'].get('dirty') else ''}). Do not edit by hand.",
         "> Exploratory. It computes NO registered fraction and NO Sobol index (prereg/dynamics.md, Tools and",
         "> foreknowledge). Parameter values are assumptions, not estimates.", "",
         f"## Morris screening ({n_eval} model evaluations)", "",
         "mu* is the mean absolute elementary effect on the sampling scale, relative to the largest for that output.",
         "Parameters with relative mu* >= 0.1, largest first:", ""]
    for o, g in mdf.groupby("output", sort=False):
        g = g.sort_values("mu_star", ascending=False)
        top = [f"{r.parameter} ({r.mu_star_rel:.2f})" for r in g.itertuples() if r.mu_star_rel >= 0.1]
        c0 = g[g.parameter == "c0"].mu_star_rel.iloc[0]
        L.append(f"- **{o}**: {', '.join(top) if top else 'none'}; dummy c0: {c0:.2g}")
    L += ["", "## One-at-a-time sweeps around the reference point", "",
          "| parameter | T* ratio atomoxetine (min–max) | T* ratio prazosin (min–max) | max number of fixed points | "
          "max bistable-window length |", "|---|---|---|---|---|"]
    for n, g in odf.groupby("parameter", sort=False):
        L.append(f"| {n} | {g.ratio_atomoxetine.min():.3f}–{g.ratio_atomoxetine.max():.3f} | "
                 f"{g.ratio_prazosin.min():.3f}–{g.ratio_prazosin.max():.3f} | {int(g.n_fixed.max())} | "
                 f"{g.bistable_window_length.max():.3g} |")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    sys.exit(main())
