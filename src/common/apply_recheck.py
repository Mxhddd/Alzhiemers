"""Apply the independent second-pass check to every extracted file.

    uv run python -m src.common.apply_recheck

Inputs (committed, data/extracted/recheck/):
  * tasks_module{2,5}.csv: what the second reader was asked to read. Each
    task gives source, locator and a description of the quantity. Stored
    values were never shown; decimals in locators were redacted.
  * results_module{2,5}.csv: what the second reader found, exactly as
    printed, with the verbatim text and notes.

For each extracted row this compares the stored numbers with the
re-read numbers and sets ``machine_rechecked``:
  * true: every number agrees (numerically, after removing thousands
    separators and the % sign of CI levels);
  * discrepancy: any number differs, a number was not found, or the second
    reader flagged that the stored description does not match the source
    (rows listed in DESCRIPTION_FLAGS below, with the reason).
The ``verified`` column is never touched: only a human sets it to true.
Writes data/extracted/recheck/recheck_log.md listing every row's outcome
and every discrepancy.
"""

from __future__ import annotations

import sys

import pandas as pd

from src.common.paths import REPO_ROOT

X = REPO_ROOT / "data" / "extracted"
RC = X / "recheck"

# file -> (stored column for each re-read field)
FIELDS = {
    "dementia_incidence_cfas.csv": {"value": "rate_per_1000_py", "ci_lower": "ci_lower", "ci_upper": "ci_upper"},
    "amyloid_prevalence_jansen2015.csv": {"value": "prevalence_pct", "ci_lower": "ci_lower_pct", "ci_upper": "ci_upper_pct"},
    "amyloid_hr_ossenkoppele2022.csv": {"value": "hr", "ci_lower": "ci_lower", "ci_upper": "ci_upper",
                                        "n_exposed": "n_exposed", "n_reference": "n_reference"},
    "braak2011_abstract_totals.csv": {"value": "value"},
    "meta_extraction.csv": {"value": "estimate", "ci_lower": "ci_lower", "ci_upper": "ci_upper", "ci_level": "ci_level"},
    "meta_validation_moraros2017.csv": {"value": "estimate", "ci_lower": "ci_lower", "ci_upper": "ci_upper",
                                        "ci_level": "ci_level"},
}
# Discrepancies in the DESCRIPTION (not the number) found by the second reader.
DESCRIPTION_FLAGS = {
    ("braak2011_abstract_totals.csv", 8): (
        "The abstract says 'Plaques generally developed in the 40s in 4% of all cases'. Read literally this is "
        "4% of ALL cases, not '4 percent of cases in that decade' as the stored unit says. The number matches; "
        "the stored unit is an interpretation of ambiguous wording. The unit text was changed to quote the source."),
}


def num(s: str, is_level: bool = False) -> float | None:
    s = str(s).strip().replace(",", "").replace(" ", "")
    if s in ("", "NOT_FOUND"):
        return None
    if s.endswith("%"):
        s = s[:-1]
    v = float(s)
    if is_level and v > 1:          # "95" / "95%" -> 0.95 (notation only)
        v = v / 100
    return v


def same(a: float | None, b: float | None) -> bool:
    if a is None or b is None:
        return False
    return abs(a - b) <= 1e-9 * max(1.0, abs(a), abs(b))


def main() -> int:
    tasks = pd.concat([pd.read_csv(RC / f, dtype=str, keep_default_na=False)
                       for f in ("tasks_module2.csv", "tasks_module5.csv")], ignore_index=True)
    res = pd.concat([pd.read_csv(RC / f, dtype=str, keep_default_na=False)
                     for f in ("results_module2.csv", "results_module5.csv")], ignore_index=True)
    res = res.set_index("task")
    log = ["# Independent second-pass check of extracted values", "",
           "Generated by `python -m src.common.apply_recheck`. The second reader saw:",
           "",
           "- the source file;",
           "- the locator, with decimals redacted;",
           "- a description of the quantity.",
           "",
           "It never saw the stored values. Its readings are in `results_module{2,5}.csv`, with the verbatim",
           "text and notes. `verified` is untouched: only a human sets it.", "",
           "| file | row | outcome | detail |", "|---|---|---|---|"]
    n_true = n_disc = 0
    for fname, cols in FIELDS.items():
        path = X / fname
        df = pd.read_csv(path, dtype=str, keep_default_na=False)
        outcome = []
        for i in range(len(df)):
            t = tasks[(tasks.file == fname) & (tasks.row == str(i))]
            if len(t) != 1:
                raise ValueError(f"{fname} row {i}: expected one recheck task, found {len(t)}")
            r = res.loc[t.task.iloc[0]]
            key = df.loc[i, "study_id"] if "study_id" in df.columns else None
            if "role" in df.columns and df.loc[i, "role"] == "ma_pooled":
                key = "pooled"                    # the pooled-estimate task names the role, not a study
            if key is not None and key not in t["read"].iloc[0]:
                raise ValueError(f"{fname} row {i} ({key}): its recheck task describes a different row; the file "
                                 "was rebuilt since the recheck - redo the recheck rather than mapping by position")
            diffs = []
            for field, col in cols.items():
                lev = field == "ci_level"
                a, b = num(df.loc[i, col], lev), num(r[field], lev)
                if not same(a, b):
                    diffs.append(f"{field}: stored {df.loc[i, col]!r} vs re-read {r[field]!r}")
            flag = DESCRIPTION_FLAGS.get((fname, i))
            if diffs or flag:
                outcome.append("discrepancy")
                n_disc += 1
                log.append(f"| {fname} | {i} | **discrepancy** | {'; '.join(diffs + ([flag] if flag else []))} |")
            else:
                outcome.append("true")
                n_true += 1
                note = str(r.get("note", "")).replace("|", "/").replace("\n", " ")
                log.append(f"| {fname} | {i} | agrees | {note[:160]} |")
        df["machine_rechecked"] = outcome
        if fname == "braak2011_abstract_totals.csv":
            df.loc[8, "unit"] = "percent ('in 4% of all cases', as worded in the abstract)"
        df.to_csv(path, index=False)
    log += ["", f"**{n_true} rows agree, {n_disc} discrepancies.**", ""]
    (RC / "recheck_log.md").write_text("\n".join(log) + "\n")
    print(f"{n_true} agree, {n_disc} discrepancies")
    return 0


if __name__ == "__main__":
    sys.exit(main())
