"""Operating characteristics of the Module 6 verdict on SIMULATED data.

    nice -n 19 python -m sim.network_calibration [--reps 200] [--perms 1000]

Runs the exact analysis code (src/network/analysis.py, verdict rule in
src/network/verdict.py) on synthetic worlds and counts the verdicts. Nothing
here touches real data; the numbers describe synthetic worlds only.

Geometry: 34 parcels per hemisphere (the Desikan-Killiany count) on a sphere;
a distance-dependent cortical connectome (the two hemispheres apart, so
inter-hemispheric edges are weak); one LC node per hemisphere wired to every
cortical node of its side with log-normal random weights. The "entorhinal"
seed is parcel 3 of each hemisphere; it is left out of the evaluation, as in
the primary analysis. A new connectome and new maps in every replicate; one
fixed set of spins.

Worlds:
  null         observed = a smooth random map unrelated to the graph
  LC true      observed = LC-seeded diffusion at tau 1 + smooth noise
  EC true      observed = entorhinal-seeded diffusion at tau 1 + smooth noise
Noise is a smooth random map scaled to `noise` times the signal's SD.
Writes manuscript/notes/module6_calibration.md.
"""

from __future__ import annotations

import argparse
import time
from collections import Counter

import numpy as np

from sim.network_sim import fibonacci_sphere, random_connectome, smooth_field
from src.common.paths import REPO_ROOT
from src.network.analysis import analyse
from src.network.diffusion import Diffuser, laplacian, seed_vector
from src.network.spin import spin_permutations
from src.network.verdict import LABELS

N_HEMI = 34
EC = 3


def world(rep: int):
    c = fibonacci_sphere(N_HEMI)
    xyz = np.vstack([c + [-1.5, 0, 0], c + [1.5, 0, 0]])
    Wc = random_connectome(xyz, scale=0.6, seed=10_000 + rep)
    n = 2 * N_HEMI + 2
    W = np.zeros((n, n))
    W[:2 * N_HEMI, :2 * N_HEMI] = Wc
    rng = np.random.default_rng(20_000 + rep)
    for k in range(2):
        side = list(range(k * N_HEMI, (k + 1) * N_HEMI))
        w = rng.lognormal(0, 1, N_HEMI)
        w *= Wc.sum(axis=1).mean() / w.sum()                     # LC degree comparable to a cortical node
        W[2 * N_HEMI + k, side] = w
        W[side, 2 * N_HEMI + k] = w
    names = [f"ctx-lh-r{i}" for i in range(N_HEMI)] + [f"ctx-rh-r{i}" for i in range(N_HEMI)] + ["LC-lh", "LC-rh"]
    return W, names, c


def smooth(c, seed):
    return np.concatenate([smooth_field(c, n_bumps=6, kappa=4.0, seed=seed),
                           smooth_field(c, n_bumps=6, kappa=4.0, seed=seed + 1)])


def wilson(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    m = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, m - h), min(1.0, m + h)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=200)
    ap.add_argument("--perms", type=int, default=1000)
    args = ap.parse_args()
    taus = np.geomspace(0.01, 50, 400)
    seeds = {"LC": ["LC-lh", "LC-rh"], "entorhinal": [f"ctx-lh-r{EC}", f"ctx-rh-r{EC}"]}
    exclude = seeds["entorhinal"]
    c = fibonacci_sphere(N_HEMI)
    perms = spin_permutations(c, c, args.perms, seed=20261021, method="hungarian")
    worlds = [("null", None, 0.0), ("LC true", "LC", 0.5), ("LC true", "LC", 1.0), ("LC true", "LC", 2.0),
              ("EC true", "entorhinal", 0.5), ("EC true", "entorhinal", 1.0), ("EC true", "entorhinal", 2.0)]
    out = {}
    t0 = time.time()
    for label, true_seed, noise in worlds:
        counts, cross = Counter(), []
        for rep in range(args.reps):
            W, names, _ = world(rep)
            if true_seed is None:
                obs = smooth(c, 50_000 + 10 * rep)
            else:
                d = Diffuser.from_laplacian(laplacian(W, "normalized"))
                x0 = seed_vector(len(names), [names.index(r) for r in seeds[true_seed]])
                sig = d.evolve(x0, 1.0)[:2 * N_HEMI]
                nz = smooth(c, 70_000 + 10 * rep)
                obs = sig / sig.std() + noise * nz / nz.std()
            res = analyse(W, names, np.arange(2 * N_HEMI), obs, perms, seeds, exclude, taus=taus,
                          laplacian_kind="normalized", method="pearson", crossover_threshold=0.95, alpha=0.05)
            counts[res.verdict] += 1
            cross.append(res.comparison.crossover if res.comparison.crossover is not None else np.nan)
        out[(label, noise)] = (counts, np.nanmedian(cross))
        print(f"{label} noise {noise}: {dict(counts)}  ({time.time() - t0:.0f} s)", flush=True)

    n = args.reps
    lines = ["# Module 6: operating characteristics of the verdict (simulated data only)", "",
             f"Generated by `python -m sim.network_calibration --reps {n} --perms {args.perms}` "
             "(the analysis code of `src/network/analysis.py`, unchanged). Synthetic worlds, described in the "
             "script's docstring: 34 parcels per hemisphere, a distance-dependent cortical connectome, one LC node "
             "per hemisphere wired to its whole hemisphere with log-normal random weights, the entorhinal seed left "
             "out of the evaluation, 400 diffusion times, "
             f"{args.perms} spins (the real analysis uses 10,000). No real data were used.", "",
             "| World | Noise / signal SD | " + " | ".join(LABELS) + " | Median crossover tau |",
             "|---|---|" + "---|" * len(LABELS) + "---|"]
    for (label, noise), (counts, mc) in out.items():
        cells = []
        for lab in LABELS:
            k = counts.get(lab, 0)
            lo, hi = wilson(k, n)
            cells.append(f"{k}/{n} ({100 * lo:.0f}–{100 * hi:.0f}%)")
        lines.append(f"| {label} | {noise if label != 'null' else '—'} | " + " | ".join(cells) + f" | {mc:.3g} |")
    lines += ["", "Intervals are Wilson 95% intervals. The null world's observed map is unrelated to the graph, so "
              "the SUPPORTS rate there is the false-positive rate of the decisive rule."]
    path = REPO_ROOT / "manuscript" / "notes" / "module6_calibration.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
