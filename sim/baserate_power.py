"""SIMULATED power study for Module 2's variant comparison (criterion 2).

    python -m sim.baserate_power --pseudo-only            (once: pseudo-true values)
    python -m sim.baserate_power --reps 20 --shard K --nshards 4 [--max-minutes 100]
    python -m sim.baserate_power --summarise              (merge shards, write summary)

Question: with the real data's structure (12 Braak-2011 stages, 10 decade
bands, 230 brains each ≈ 2,300 brains), how often does the pre-registered
cross-validation comparison come out supports / against / inconclusive?

Truths (SIMULATION SETTINGS, not data; backbone = the dry run's,
src/baserate/run_baserate.py::SIM_TRUTH):
  * LC-first, NO amyloid effect, age slope on the c -> 1a step of 0, 0.1 and
    0.3 per decade (the null scenarios required by the 2026-10-13 revision;
    under these the correct reading is A), generated by the age-adjusted
    variant A with HR_A = 1;
  * B (independent cortical entry; common entry rate at age 50 equal to the
    LC-first world's, slope 0.1/decade);
  * C (2 hits, log rate -3.5).
For every truth, each data set is analysed exactly as criterion 2 prescribes:
A (age-adjusted), B and C are fitted, 5-fold CV by whole age band (bands
dealt round-robin), summed held-out log-likelihood, margin 2, three-way
verdict (src.baserate.run_baserate.cv_verdict_3way).

Simplifications (stated, not hidden):
  * full-data fits start from each model's pseudo-true value for that truth
    (its best fit to the EXPECTED counts, found once with fit_mle: the true
    model from the truth, wrong models from 3 random starts, each verified
    by the Newton decrement);
  * each fold starts from the full-data fit, with no further random starts
    (the analysis itself uses 20 and 4);
  * replicate fits are plain L-BFGS-B on exact gradients without the
    Newton/Hessian verification (too costly for ~2,000 fits). Instead the
    largest projected gradient is recorded per replicate and replicates
    above 1e-2 are flagged;
  * one likelihood is compiled per model with counts and fold masks as
    arguments (src.baserate.jaxlik.make_loglik_family); held-out bands stay
    on the integration grid.

Checkpointing: each finished replicate is appended to
results/dryrun/power/baserate_power_reps.csv and pseudo-true values are
cached in pseudo_true.json; rerunning skips finished work. --max-minutes
stops cleanly between replicates (exit code 3). The summary table (with
Wilson 95% intervals) is rewritten after every replicate.
"""

from __future__ import annotations

import argparse
import json
import sys
import time

import numpy as np
import pandas as pd

from sim.baserate_sim import simulate_counts
from src.baserate.data import StageCounts
from scipy.optimize import minimize

from src.baserate.fit import bounds_for, fit_mle
from src.baserate.jaxlik import make_loglik_family
from src.baserate.model import AGatedAge, BIndependent, ChainSpec, CMultiHit
from src.baserate.predict import age_band_folds
from src.baserate.run_baserate import SIM_TRUTH, cv_verdict_3way, simulated_inputs
from src.baserate.solve import stage_probabilities
from src.common.config import load_config
from src.common.paths import CONFIG_DIR, RESULTS_DIR
from src.common.runlog import start_run

OUT = RESULTS_DIR / "dryrun" / "power"
POWER_STEP = 0.5
N_PER_BAND = 230
BANDS = [(lo, lo + 10) for lo in range(1, 101, 10)]


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (np.nan, np.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=0)
    ap.add_argument("--max-minutes", type=float)
    ap.add_argument("--shard", type=int, default=0)
    ap.add_argument("--nshards", type=int, default=1)
    ap.add_argument("--pseudo-only", action="store_true")
    ap.add_argument("--summarise", action="store_true")
    args = ap.parse_args(argv)
    t_start = time.time()
    cfg = load_config(CONFIG_DIR / "baserate.yaml")
    spec = ChainSpec.from_labels([str(s) for s in cfg.get("data.stage_order")], cfg.get("data.first_cortical_stage"))
    # Step 0.5 y inside the power study only (the analysis uses the audited
    # step, >= 0.125): the log-likelihood differs by ~0.001 units from a
    # 0.05-y step on this problem (measured), negligible against the margin
    # of 2, and it halves the cost of ~1,800 fits.
    step, start = POWER_STEP, cfg.get("solver.start_age")
    centre, scale = cfg.get("solver.age_centre"), cfg.get("solver.age_scale")
    k, margin = cfg.get("cross_validation.k"), cfg.get("cross_validation.margin")
    mle = dict(cfg.get("mle"))
    inp, _ = simulated_inputs(cfg, spec, step, start, centre, scale)
    amy = inp.amyloid["primary"]
    A, B, C = AGatedAge(spec, amy, centre, scale), BIndependent(spec, centre, scale), CMultiHit(spec, 2, centre, scale)
    models = {"A_gated_age": A, "B_independent": B, "C_multihit": C}

    def theta_for(m, extra):
        d = dict(SIM_TRUTH, **extra)
        return np.array([d[n] for n in m.param_names])

    truths = {
        "LC-first, no amyloid, c->1a slope 0": (A, theta_for(A, {"beta_mu": 0.0, "log_hr_amyloid": 0.0})),
        "LC-first, no amyloid, c->1a slope 0.1": (A, theta_for(A, {"beta_mu": 0.1, "log_hr_amyloid": 0.0})),
        "LC-first, no amyloid, c->1a slope 0.3": (A, theta_for(A, {"beta_mu": 0.3, "log_hr_amyloid": 0.0})),
        "B independent": (B, theta_for(B, {"a_nu": SIM_TRUTH["log_mu0"] + np.log(1.05), "b_nu": 0.1})),
        "C multi-hit (2 hits)": (C, theta_for(C, {"log_lambda": -3.5})),
    }
    template = [StageCounts(float(lo), float(hi), "SIMULATED", np.zeros(len(spec.stages))) for lo, hi in BANDS]
    folds = np.array(age_band_folds(template, k))
    OUT.mkdir(parents=True, exist_ok=True)
    reps_csv = OUT / f"baserate_power_reps_shard{args.shard}.csv"

    with start_run(module="baserate_power_sim", config_path=CONFIG_DIR / "baserate.yaml", seed=cfg.get("seed"),
                   packages=["numpy", "scipy", "jax"]) as run:
        run.mark_simulated()
        fam = {n: make_loglik_family(m, template, step=step, start_age=start) for n, m in models.items()}

        def light_fit(m, mname, counts, mask, x0):
            """Warm-started L-BFGS-B; returns (theta, loglik, max projected gradient)."""
            vg = fam[mname][1]
            box = bounds_for(m, mle)
            lo = np.array([b[0] for b in box]); hi = np.array([b[1] for b in box])

            def f(th):
                v, g = vg(th, counts, mask)
                v, g = float(v), np.asarray(g, dtype=float)
                if not np.isfinite(v) or not np.all(np.isfinite(g)):
                    return 1e300, np.zeros_like(th)
                return -v, -g

            r = minimize(f, np.clip(np.asarray(x0, float), lo, hi), jac=True, method="L-BFGS-B", bounds=box,
                         options={"maxiter": 3000, "ftol": 1e-12, "gtol": 1e-6})
            g = r.jac
            free = ~(((r.x <= lo + 1e-10) & (g > 0)) | ((r.x >= hi - 1e-10) & (g < 0)))
            return r.x, -r.fun, float(np.max(np.abs(g[free]))) if free.any() else 0.0

        def bound(name, counts, mask):
            ll, vg, h = fam[name]
            return (lambda th: ll(th, counts, mask), lambda th: vg(th, counts, mask), lambda th: h(th, counts, mask))

        pseudo = {}
        for f in sorted(OUT.glob("pseudo_true*.json")):     # merged over --pseudo-only shards
            pseudo.update(json.loads(f.read_text()))
        done = pd.read_csv(reps_csv) if reps_csv.exists() else pd.DataFrame(columns=["truth", "rep"])
        ones = np.ones(len(BANDS))

        def write_summary():
            shards = sorted(OUT.glob("baserate_power_reps_shard*.csv"))
            if not shards:
                return
            df = pd.concat([pd.read_csv(f) for f in shards], ignore_index=True)
            df = df.sort_values(["truth", "rep"], key=lambda c: c.map(list(truths).index) if c.name == "truth" else c)
            rows = []
            for t, g in df.groupby("truth", sort=False):
                n = len(g)
                row = {"truth": t, "n_datasets": n}
                for v in ("supports", "AGAINST", "inconclusive"):
                    kv = int((g["verdict"] == v).sum())
                    lo, hi = wilson(kv, n)
                    row.update({f"P({v})": kv / n, f"P({v})_lo95": lo, f"P({v})_hi95": hi})
                for mname in models:
                    row[f"P(best={mname})"] = float((g["cv_best"] == mname).mean())
                row["median CV gap A-B"] = float((g["cv_A_gated_age"] - g["cv_B_independent"]).median())
                row["median CV gap A-C"] = float((g["cv_A_gated_age"] - g["cv_C_multihit"]).median())
                rows.append(row)
            run.write_table(pd.DataFrame(rows), OUT / "baserate_power_summary.csv")

        for ti, (tname, (tm, th)) in enumerate(truths.items()):
            P = stage_probabilities(tm, th, [(lo + hi) / 2 for lo, hi in BANDS], step=step, start_age=start)
            if tname not in pseudo and args.summarise:
                continue
            if args.pseudo_only and ti % args.nshards != args.shard:
                continue
            if tname not in pseudo:
                if not args.pseudo_only:
                    raise RuntimeError(f"no pseudo-true values for '{tname}': run with --pseudo-only first "
                                       "(shards must not compute them concurrently)")
                expected = (N_PER_BAND * P / P.sum(axis=1, keepdims=True))
                pseudo[tname] = {}
                for mname, m in models.items():
                    ws = [th] if m is tm else None
                    f = fit_mle(m, [], step=step, start_age=start, cfg_mle=mle, seed=7,
                                n_random=0 if m is tm else 3, extra_starts=ws, compiled=bound(mname, expected, ones))
                    pseudo[tname][mname] = f.theta.tolist()
                    run.info(f"pseudo-true {mname} under '{tname}': expected-count logLik {f.loglik:.2f}")
                mine = {t: v for t, v in pseudo.items() if t == tname}
                f_out = OUT / f"pseudo_true_{ti}.json"
                f_out.write_text(json.dumps(mine, indent=1))
            if args.pseudo_only or args.summarise:
                continue
            for r in range(args.reps):
                if (ti * 1000 + r) % args.nshards != args.shard:
                    continue
                if ((done["truth"] == tname) & (done["rep"] == r)).any():
                    continue
                if args.max_minutes is not None and (time.time() - t_start) / 60 > args.max_minutes:
                    run.warning(f"time budget spent: stopping before '{tname}' rep {r}; rerun to continue")
                    print("INCOMPLETE: rerun to continue", file=sys.stderr)
                    return 3
                t0 = time.time()
                data = simulate_counts(tm, th, BANDS, N_PER_BAND, step=step, start_age=start,
                                       seed=100_000 + 1_000 * ti + r)
                counts = np.array([g.counts for g in data], dtype=float)
                row = {"truth": tname, "rep": r}
                worst = 0.0
                for mname, m in models.items():
                    th_full, ll_full, pg = light_fit(m, mname, counts, ones, pseudo[tname][mname])
                    worst = max(worst, pg)
                    held = 0.0
                    for f in range(k):
                        train = (folds != f).astype(float)
                        th_f, _, pg = light_fit(m, mname, counts, train, th_full)
                        worst = max(worst, pg)
                        held += float(fam[mname][0](th_f, counts, 1.0 - train))
                    row[f"full_{mname}"] = ll_full
                    row[f"cv_{mname}"] = held
                row["max_projected_gradient"] = worst
                row["flag_unconverged"] = worst > 1e-2
                cv_df = pd.DataFrame({"model": list(models), "cv_heldout_loglik": [row[f"cv_{n}"] for n in models]})
                row["verdict"] = cv_verdict_3way(cv_df, margin, "A_gated_age").split(" (")[0]
                row["cv_best"] = cv_df.sort_values("cv_heldout_loglik").iloc[-1]["model"]
                row["seconds"] = time.time() - t0
                pd.DataFrame([row]).to_csv(reps_csv, mode="a", header=not reps_csv.exists(), index=False)
                done = pd.concat([done, pd.DataFrame([row])], ignore_index=True)
                run.info(f"{tname} rep {r}: {row['verdict']} (best {row['cv_best']}), {row['seconds']:.0f} s")
                try:            # outputs after every replicate, merged over all shards written so far
                    write_summary()
                except Exception as e:      # another shard may be mid-append; the next replicate retries
                    run.warning(f"summary not rewritten this time ({type(e).__name__}: {e})")
        if args.summarise:
            write_summary()
        run.info("POWER STUDY COMPLETE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
